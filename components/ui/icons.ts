export function iconUri(path: string): string {
  const svg =
    '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">' +
    path +
    "</svg>";
  return "data:image/svg+xml," + encodeURIComponent(svg);
}

export function maskStyle(path: string, size?: number, color?: string): CSSProperties {
  const uri = "url('" + iconUri(path) + "') center/contain no-repeat";
  return {
    display: "inline-block",
    width: (size || 18) + "px",
    height: (size || 18) + "px",
    background: color || "currentColor",
    WebkitMask: uri,
    mask: uri,
    flex: "none",
  };
}

/** İkon adı verilirse ICONS'tan, değilse ham path kabul eder */
export function iconPath(name: string): string {
  return ICONS[name] ?? name;
}
